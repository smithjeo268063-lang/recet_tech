create table if not exists public.catalog_brands (
  slug text primary key,
  name text not null,
  description text not null default '',
  logo text not null default '',
  is_active boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.catalog_categories (
  slug text primary key,
  title text not null,
  description text not null default '',
  image text not null default '',
  is_active boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.catalog_products (
  id bigint generated by default as identity (start with 1000000) primary key,
  slug text not null unique,
  title text not null,
  category text not null,
  brand text not null,
  price numeric(14, 2) not null check (price >= 0),
  compare_at numeric(14, 2) not null default 0 check (compare_at >= 0),
  rating numeric(3, 2) not null default 0 check (rating >= 0 and rating <= 5),
  reviews integer not null default 0 check (reviews >= 0),
  image text not null default '',
  images jsonb not null default '[]'::jsonb,
  summary text not null default '',
  tags jsonb not null default '[]'::jsonb,
  features jsonb not null default '[]'::jsonb,
  specifications jsonb not null default '[]'::jsonb,
  inventory integer not null default 0 check (inventory >= 0),
  is_featured boolean not null default false,
  is_new boolean not null default false,
  is_deal boolean not null default false,
  is_uk_used boolean not null default false,
  is_published boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.storefront_content (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.catalog_brands enable row level security;
alter table public.catalog_categories enable row level security;
alter table public.catalog_products enable row level security;
alter table public.storefront_content enable row level security;

drop policy if exists "Public can read active catalog brands" on public.catalog_brands;
create policy "Public can read active catalog brands"
  on public.catalog_brands for select to anon, authenticated
  using (is_active);

drop policy if exists "Public can read active catalog categories" on public.catalog_categories;
create policy "Public can read active catalog categories"
  on public.catalog_categories for select to anon, authenticated
  using (is_active);

drop policy if exists "Public can read published catalog products" on public.catalog_products;
create policy "Public can read published catalog products"
  on public.catalog_products for select to anon, authenticated
  using (is_published);

drop policy if exists "Public can read storefront content" on public.storefront_content;
create policy "Public can read storefront content"
  on public.storefront_content for select to anon, authenticated
  using (true);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'catalog-images',
  'catalog-images',
  true,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp', 'image/avif']
)
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Public can read catalog images" on storage.objects;
create policy "Public can read catalog images"
  on storage.objects for select to anon, authenticated
  using (bucket_id = 'catalog-images');
